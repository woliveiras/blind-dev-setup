#!/usr/bin/env python3
"""Collect notices for the modules actually linked into the Windows executable."""

import json
import os
from pathlib import Path
import subprocess


ROOT = Path(__file__).resolve().parent.parent


def objects(raw):
    decoder = json.JSONDecoder()
    while raw.strip():
        raw = raw.lstrip()
        item, end = decoder.raw_decode(raw)
        yield item
        raw = raw[end:]


environment = dict(os.environ, GOOS="windows", GOARCH="amd64", CGO_ENABLED="0")
packages = subprocess.check_output(
    ["go", "list", "-deps", "-json", "./cmd/blind-dev-setup"],
    cwd=ROOT, env=environment, text=True,
)
modules = {}
for package in objects(packages):
    module = package.get("Module")
    if module and not module.get("Main"):
        modules[module["Path"]] = module

goroot = Path(subprocess.check_output(["go", "env", "GOROOT"], text=True).strip())
sections = [
    "Third-party notices for blind-dev-setup\n"
    "Generated by scripts/update-go-notices.py for windows/amd64.\n",
    "Go standard library and runtime\n\n" + (goroot / "LICENSE").read_text(),
]
for name, module in sorted(modules.items()):
    directory = Path(module["Dir"])
    licenses = sorted(
        path for path in directory.iterdir()
        if path.is_file() and path.name.upper().startswith(("LICENSE", "COPYING", "NOTICE"))
    )
    # This released module records its license/author in README, without a
    # separate LICENSE file. Preserve those original notices verbatim.
    if name == "github.com/mattn/go-localereader" and module["Version"] == "v0.0.1":
        readme = (directory / "README.md").read_text()
        marker = "## License"
        if marker not in readme or "MIT" not in readme.partition(marker)[2]:
            raise SystemExit(f"License notice changed for {name}")
        sections.append(f"{name} {module['Version']}\nhttps://{name}\n\n" + marker + readme.partition(marker)[2])
        continue
    if not licenses:
        raise SystemExit(f"No license notice found for {name}; review it before distributing.")
    sections.append(f"{name} {module['Version']}\nhttps://{name}\n")
    for license_file in licenses:
        sections.append(f"{license_file.name}\n\n{license_file.read_text()}")

destination = ROOT / "internal/notices/THIRD-PARTY-NOTICES.txt"
destination.write_text("\n" + ("\n" + "=" * 72 + "\n\n").join(sections), encoding="utf-8")
print(f"Wrote notices for Go and {len(modules)} modules to {destination.relative_to(ROOT)}")
